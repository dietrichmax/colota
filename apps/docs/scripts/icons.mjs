// Writes assets/icons.svg, a sprite of the Lucide glyphs the site uses, taken from the app's installed
// lucide-react-native so both draw the same version. Run by hand after adding a name; the output is committed.
import { existsSync, readFileSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const NAMES = [
  "arrow-up-right",
  "book-open",
  "chevron-down",
  "chevron-left",
  "chevron-right",
  "copy",
  "download",
  "external-link",
  "house",
  "info",
  "lightbulb",
  "moon",
  "octagon-alert",
  "pencil",
  "qr-code",
  "route",
  "server",
  "shield-check",
  "sparkles",
  "sun",
  "triangle-alert",
  "upload",
  "waypoints",
  "wifi-off",
  "x"
]

const docsRoot = join(dirname(fileURLToPath(import.meta.url)), "..")
const iconDir = join(docsRoot, "..", "..", "node_modules", "lucide-react-native", "dist", "esm", "icons")
const pkg = JSON.parse(readFileSync(join(iconDir, "..", "..", "..", "package.json"), "utf8"))
const esc = (value) => String(value).replace(/&/g, "&amp;").replace(/"/g, "&quot;")

const symbols = NAMES.map((name) => {
  const file = join(iconDir, `${name}.mjs`)
  if (!existsSync(file)) throw new Error(`No Lucide icon named ${name} in lucide-react-native ${pkg.version}`)
  const match = readFileSync(file, "utf8").match(/const __iconData = (\{[\s\S]*?\n\});/)
  if (!match) throw new Error(`Cannot read the icon data in ${file}`)
  const data = Function(`return (${match[1]})`)()
  const children = data.node
    .map(([tag, attrs]) => {
      const list = Object.entries(attrs)
        .filter(([key]) => key !== "key")
        .map(([key, value]) => `${key}="${esc(value)}"`)
      return `<${tag} ${list.join(" ")} vector-effect="non-scaling-stroke"/>`
    })
    .join("")
  return `<symbol id="i-${name}" viewBox="0 0 24 24">${children}</symbol>`
})

const sprite = `<!-- Generated by scripts/icons.mjs from lucide-react-native ${pkg.version} (ISC). Do not edit. -->
<svg xmlns="http://www.w3.org/2000/svg" style="display:none">
${symbols.join("\n")}
</svg>
`
writeFileSync(join(docsRoot, "assets", "icons.svg"), sprite)
