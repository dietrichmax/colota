// Writes assets/css/tokens.css and data/links.json from packages/shared, read as TypeScript by Node itself.
import { mkdirSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"
import { darkColors, lightColors, STATE_LAYER_ALPHA } from "../../../packages/shared/src/colors.ts"
import { space } from "../../../packages/shared/src/space.ts"
import { radius } from "../../../packages/shared/src/radius.ts"
import { size } from "../../../packages/shared/src/size.ts"
import { fontFamily, fontSizes } from "../../../packages/shared/src/typography.ts"
import * as links from "../../../packages/shared/src/links.ts"
import { TRIP_COLORS } from "../../../packages/shared/src/tripColors.ts"

const docsRoot = join(dirname(fileURLToPath(import.meta.url)), "..")
const kebab = (name) => name.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`)
const px = (value) => (value === 0 ? "0" : `${value}px`)

const colorVars = (colors) =>
  Object.entries(colors)
    .map(([name, value]) => `  --color-${kebab(name)}: ${value};`)
    .join("\n")

const scale = (prefix, values) =>
  Object.entries(values)
    .filter(([, value]) => typeof value === "number")
    .map(([name, value]) => `  --${prefix}-${kebab(name)}: ${px(value)};`)
    .join("\n")

const css = `/* Generated by scripts/tokens.mjs from packages/shared. Do not edit. */
:root {
${colorVars(lightColors)}
  --state-layer-alpha: ${parseInt(STATE_LAYER_ALPHA, 16) / 255};
${TRIP_COLORS.map((color, i) => `  --trip-${i + 1}: ${color};`).join("\n")}
${scale("space", space)}
${scale("radius", radius)}
${scale("size", size)}
${scale("icon", size.icon)}
${scale("fs", fontSizes)}
  --font: "${fontFamily}", system-ui, -apple-system, "Segoe UI", Roboto, sans-serif;
  color-scheme: light;
}
@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
${colorVars(darkColors).replace(/^/gm, "  ")}
    color-scheme: dark;
  }
}
:root[data-theme="dark"] {
${colorVars(darkColors)}
  color-scheme: dark;
}
`

mkdirSync(join(docsRoot, "assets", "css"), { recursive: true })
mkdirSync(join(docsRoot, "data"), { recursive: true })
writeFileSync(join(docsRoot, "assets", "css", "tokens.css"), css)
writeFileSync(join(docsRoot, "data", "links.json"), JSON.stringify({ ...links }, null, 2) + "\n")
